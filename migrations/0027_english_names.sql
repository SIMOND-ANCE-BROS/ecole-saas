-- 6. Immutability triggers (payments, audit log): renamed; the payment function compares rows
--    without the column tool_synced (formerly synchro_outil), so its body is rewritten.
ALTER FUNCTION "paiement_inalterable"() RENAME TO "payment_immutable";
CREATE OR REPLACE FUNCTION "payment_immutable"() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'A payment cannot be deleted: record a negative payment';
  END IF;
  IF (to_jsonb(NEW) - 'tool_synced') <> (to_jsonb(OLD) - 'tool_synced') THEN
    RAISE EXCEPTION 'A payment cannot be modified: record a correcting payment';
  END IF;
  RETURN NEW;
END $$;
ALTER TRIGGER "paiement_inalterable" ON "payment" RENAME TO "payment_immutable";
ALTER FUNCTION "journal_ajout_seul"() RENAME TO "audit_log_append_only";
CREATE OR REPLACE FUNCTION "audit_log_append_only"() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'The audit log can be neither modified nor deleted';
END $$;
ALTER TRIGGER "journal_ajout_seul" ON "audit_log" RENAME TO "audit_log_append_only";

